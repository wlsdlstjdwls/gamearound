// 인기순위 순번을 다루는 규칙. 쓰는 쪽(server/sync)과 읽는 쪽(server/services)이 같은 값을 봐야 해서
// 어느 한쪽이 아니라 여기 둔다 — 수집 예산이 아니라 "무엇을 인기로 칠 것인가" 라는 규칙이다.

/**
 * 순번을 믿을 수 있는 기간(일). 이 날수보다 오래된 순번은 없는 값으로 친다.
 *
 * 왜 필요한가: 순위에서 빠진 게임은 갱신할 기회가 없어 마지막 순번으로 굳는다.
 * 지난달 50위였다가 목록 밖으로 나간 게임이 오늘 200위인 게임을 영원히 앞서면
 * 화면의 "인기순" 은 "한때 인기였던 순" 이 된다.
 *
 * 거르는 일을 읽는 쪽이 하는 이유: 쓰는 쪽은 지울 수 없다. 목록 밖으로 나간 게임은 다음 수집에
 * 나타나지 않으므로 아무도 그 행을 찾아가지 않는다 — 낡음은 값이 아니라 시각으로만 드러난다.
 *
 * 14일인 근거: 인기순위 수집이 한 번에 상위 2,000위를 훑고(POPULARITY_RANK_PAGES) 약 47초다.
 * 순위 안에 있는 게임은 그 작업이 도는 날마다 갱신되므로, 2주는 며칠 걸러 돌려도 순위가
 * 통째로 비지 않을 만큼의 여유다.
 */
export const POPULARITY_RANK_MAX_AGE_DAYS = 14;

/**
 * 평가 수를 순번 자리로 바꾸는 보정표. `[자리, 그 자리에 필요한 평가 수]` 가 내림차순으로 온다.
 *
 * **왜 이런 표가 필요한가.** 순번을 주는 스토어는 steam 과 psstore 둘뿐이다. Xbox 는 순번이 0%고
 * (목록 정렬을 못 바꾼다) 평가 수만 81% 준다. 그런데 정렬 첫 키가 순번이라 순번 없는 게임은
 * **실측 1,877건 뒤에서** 시작했다 — 24칸 기준 78페이지 뒤라 Xbox 게임은 인기순에 사실상 없었다.
 *
 * **왜 이 숫자인가.** steam 은 순번과 평가 수를 **둘 다** 주는 유일한 소스다. 그 1,432건에서
 * 둘의 관계를 실측했더니 순번 구간별 평가 수 중앙값이 단조로 떨어졌다
 * (1~100위 56,114 / 101~300위 30,911 / 601~1000위 9,033 / 1501~2000위 2,878).
 * 평가 수는 순번을 대신할 수 있는 값이다. 이 표는 그 1,432건의 평가 수 분포를 100자리마다 끊은 것이다.
 * 즉 "그 자리를 차지한 게임이 실제로 받은 평가 수" 이지 지어낸 경계가 아니다.
 *
 * **1,300 에서 끊는 이유.** 1,400 자리의 경계가 평가 93 이고 1,500 부터는 4 다. 그 아래는
 * 변별력이 없어 자리를 주는 것이 오히려 거짓말이 된다. 애매한 뒷줄은 섞지 않고 그대로 둔다.
 *
 * **낡으면 어떻게 고치나.** steam 순번 보유 행의 평가 수를 내림차순으로 세워 100번째마다 읽으면 된다.
 * 카탈로그가 커지면 경계가 올라간다 — 2026-09-21 실측값이다.
 */
const REVIEW_RANK_TABLE: ReadonlyArray<readonly [position: number, reviews: number]> = [
  [100, 180637], [200, 85683], [300, 46879], [400, 31038], [500, 19578],
  [600, 12393], [700, 8650], [800, 5450], [900, 3465], [1000, 2231],
  [1100, 1372], [1200, 777], [1300, 384],
];

/**
 * 할인 줄의 "별점 높은순" 이 점수를 믿기 시작하는 평가 수(2026-09-29 사용자 지정: 100명).
 *
 * 점수만 보면 다섯 명이 준 100점이 5만 명이 준 90점을 이긴다. 할인 줄에서 별점은 판매 순번 다음,
 * 환산 자리 앞에 서는 키라 여기를 통과한 행은 수천 개의 순번 없는 게임 앞에 선다 — 문턱이 없으면
 * 그 앞줄을 평가 몇 개짜리 인디가 차지한다. 100 은 평가 수 환산표가 자리를 주기 시작하는 384 보다 낮아,
 * 환산 자리를 못 받은 괜찮은 게임도 별점으로는 앞에 설 수 있다.
 */
export const RATING_MIN_REVIEWS = 100;

/** 위 표를 SQL CASE 로 옮길 때 쓰는 읽기 전용 사본. 두 곳이 같은 숫자를 봐야 한다 */
export const REVIEW_RANK_STEPS = REVIEW_RANK_TABLE;

/**
 * HLTB 기록 인원수를 순번 자리로 바꾸는 보정표. `[자리, 그 자리에 필요한 인원]` 내림차순.
 *
 * **왜 두 번째 표가 필요한가.** 평가 수 표(REVIEW_RANK_TABLE)는 Xbox 를 구했지만 스위치와 Epic 은
 * 못 구한다 — 그 스토어들은 평가 수도 안 준다. 두 스토어 다 정렬 입구가 아예 없다는 것을 실측했고
 * (각 어댑터의 listPopularPages 주석), 남은 길은 스토어 밖이었다. HLTB 는 기기를 가리지 않는다.
 *
 * **왜 이 숫자인가.** 뜬 방법은 평가 수 표와 같다: 순번을 가진 게임 1,196건의 기록 인원수를
 * 내림차순으로 세워 100번째마다 읽었다(2026-09-21 실측). 순번 구간별 중앙값도 단조로 떨어진다
 * (1~100위 475 / 101~300위 285 / 301~600위 214 / 601~1000위 131).
 *
 * **700 에서 끊는 이유.** 800 자리의 경계가 29명이고 그 아래는 14, 5, 1 이다. 그리고 순번
 * 1001~1500위 구간의 중앙값(28)이 1501~2000위(49)보다 낮아 단조가 깨진다 — 그 아래는 변별력이
 * 없어 자리를 주는 것이 오히려 거짓말이 된다.
 *
 * **표본 편향을 확인했고 보정하지 않기로 했다.** 순번 상위인데 기록이 거의 없는 무리가 둘 있다:
 * 미출시작(GTA VI 5명, NBA 2K27 2명)과 한국, 아시아 라이브서비스 게임(블루 아카이브 40명,
 * 이터널 리턴 3명). HLTB 가 서양 클리어 기록 커뮤니티라 후자는 구조적으로 낮다. 그런데 이 값들은
 * 내림차순의 **바닥**에 모여 위쪽 경계를 건드리지 않는다 — 미출시작 18건을 빼고 다시 떠도
 * 100 자리가 4,879 로 같고 300 자리만 841 에서 840 으로 움직인다. 거를 이유가 없다.
 *
 * 애초에 이 표는 순번이 **없을 때만** 쓰인다. 저 게임들은 전부 진짜 순번을 갖고 있어 여기까지 오지 않는다.
 *
 * **낡으면 어떻게 고치나.** `pnpm hltb:popularity --ranked` 로 재료를 채우고 `pnpm hltb:table` 로 뜬다.
 * 그 스크립트가 구간별 중앙값과 거르기 전후 표를 같이 내주므로, 단조가 깨지는 자리에서 끊으면 된다.
 */
const HLTB_RANK_TABLE: ReadonlyArray<readonly [position: number, logged: number]> = [
  [100, 4879], [200, 1985], [300, 841], [400, 466], [500, 249], [600, 123], [700, 64],
];

/**
 * HLTB 환산 자리를 통째로 밀어 내리는 값. 표가 준 자리에 이 수를 더해 쓴다.
 *
 * **왜 내리나.** `count_comp` 는 누적값이다. Assassin's Creed II 가 19,917명, Halo 3 이 5,876명인데
 * 16년 모은 숫자고, Mario Kart World 의 1,812명은 1년 모은 숫자다. 표를 그대로 쓰면 저 옛 게임들이
 * **13,000위에서 173위로** 뛰어 지금 팔리는 게임 앞에 선다(2026-09-21 실측). 그건 인기순이 아니라
 * "한때 인기였던 순" 이고, POPULARITY_RANK_MAX_AGE_DAYS 가 실제 순번에서 막고 있는 바로 그것이다.
 *
 * 평가 수 환산은 같은 문제를 안 겪는다. 그 값은 스토어가 그 상품에 달아 준 것이라
 * 카탈로그에서 내려가면 같이 멈추는데, HLTB 기록은 스토어와 무관하게 계속 쌓인다.
 *
 * **왜 2000 인가.** 우리가 실제 순번을 받는 범위의 끝이다(POPULARITY_RANK_PAGES 로 steam 2,000위,
 * psstore 960위까지 훑는다). 이 수를 더하면 HLTB 자리는 **실제 순번과 평가 수 환산 뒤, 자리를 전혀
 * 못 받은 게임 앞**에 온다. 스위치와 Epic 이 노리던 것이 그것이다 — 앞줄을 뺏는 것이 아니라
 * 11,443건 뒤에서 시작하지 않는 것.
 *
 * 띠 안의 순서는 표가 정한다. 그래서 스위치끼리는 여전히 기록 인원수로 갈린다.
 */
export const HLTB_RANK_OFFSET = 2000;

/** 위 표를 SQL CASE 로 옮길 때 쓰는 읽기 전용 사본. 두 곳이 같은 숫자를 봐야 한다 */
export const HLTB_RANK_STEPS = HLTB_RANK_TABLE;

/**
 * 기록 인원수를 순번 자리로 바꾼다. 자리를 줄 수 없으면 null 이다.
 *
 * 평가 수와 달리 **유료 여부를 보지 않는다.** 그 조건은 무료 캐주얼이 평가 수로 앞줄을 먹는 것을
 * 막으려던 것인데(Candy Crush 가 Forza 를 이겼다), HLTB 기록은 "끝까지 해 본 사람" 이라
 * 그 방식으로 부풀지 않는다. 무료 게임의 가격이 null 인 스토어도 있어 조건을 걸면 진짜 게임이 같이 죽는다.
 */
export function pseudoRankFromHltb(logged: number | null | undefined): number | null {
  if (logged == null || !Number.isFinite(logged)) return null;
  for (const [position, needed] of HLTB_RANK_TABLE) {
    if (logged >= needed) return position + HLTB_RANK_OFFSET;
  }
  return null;
}

/**
 * 평가 수를 순번 자리로 바꾼다. 자리를 줄 수 없으면 null 이다.
 *
 * **유료 게임에만 준다.** 무료 게임의 평가 수는 인기를 뜻하지 않는다 — Xbox 전용 무료 상위가
 * Candy Crush Saga(127만), Microsoft Mahjong(38만), Microsoft Sudoku(15만)이고
 * Forza Horizon 4 가 일곱 번째다. 값으로 캐주얼을 가르려 해도 안 된다(Crossout, Vigor,
 * Trove, Throne and Liberty 는 진짜 무료 게임이다). 그래서 무료에는 자리를 주지 않고,
 * 스토어가 실제 순번을 준 무료 게임만 앞에 선다(원신, Warframe 이 그 경우다).
 *
 * 값을 모르는 것(null)과 무료(0)를 섞지 않는다 — 가격이 없는 행은 근거가 없는 것이라 자리도 없다.
 */
export function pseudoRankFromReviews(reviews: number | null | undefined, paid: boolean): number | null {
  if (!paid || reviews == null || !Number.isFinite(reviews)) return null;
  for (const [position, needed] of REVIEW_RANK_TABLE) {
    if (reviews >= needed) return position;
  }
  return null;
}
