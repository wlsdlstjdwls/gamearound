// 목록 격자 설정 — 서버가 그리는 첫 페이지, 이어 붙이는 페이지, 기다리는 동안의 뼈대가 모두 같은 값을 써야
// 카드 폭이 경계에서 바뀌지 않는다.
//
// 왜 components/games-infinite 가 아니라 lib 인가(2026-09-15): 그 파일은 "use client" 라
// 서버 컴포넌트(games/skeletons)가 여기서 상수를 가져오면 문자열이 아니라 클라이언트 참조가 넘어온다.
// 실제로 뼈대의 class 자리에 함수 소스가 박혀 격자가 풀렸고, 한 페이지치 카드가 세로로 쌓이면서
// 문서 높이가 몇 배로 튀었다 — 필터를 누를 때마다 화면이 통째로 흔들린 원인이 이것이다.
// 상수는 클라이언트 경계가 없는 곳에 둔다.
// 세로 간격이 가로보다 넓다(36 대 24): 할인 스탬프가 커버 아래로 14px 나와 있어
// 같은 간격이면 아랫줄 카드의 커버를 건드린다.
// min() 을 씌우는 이유: auto-fill 의 minmax 는 화면이 그 값보다 좁아도 칸을 줄이지 않는다 —
// 320px 기기에서 280px 칸 + 좌우 여백이 화면을 넘어 목록이 통째로 가로로 밀렸다.
//
// 최소 폭이 홈(280)보다 좁은 이유: 이 화면은 왼쪽에 232px 필터 기둥이 선다. 1200px 기둥에서
// 목록에 남는 폭은 880px 인데, 280 으로 두면 3열에 888px 이 필요해 8px 차이로 2열이 된다 —
// 데스크톱 한 화면에 카드가 넷만 남았다. 258 은 그 자리에서 3열이 서는 값이다(3x258 + 2x24 = 822).
//
// 2026-09-30: 열 수를 **못 박았다**(사용자: "한 행에 4개씩", "게임 목록에서는 한 행에 3개씩").
// 최소폭(auto-fill)으로 두면 홈(1200)은 5열, 목록(필터 옆 880)은 4열로 화면마다 카드 크기가 달랐다.
// 목록은 왼쪽에 필터 기둥이 서서 3열이어야 카드 폭이 홈 4열과 같아진다(약 270px) — 같은 카드가 같은 크기다.
// 칸 수(HOME_LIMIT 24, GAMES_PAGE_SIZE 36)는 1, 2, 3, 4 로 모두 나눠떨어진다 — 마지막 줄이 이 빠지지 않는다.
// 좁은 화면은 **한 줄에 한 장**(2026-09-30, 사용자: "모바일은 1행에 1개씩, 컨텐츠가 너무 작아서 안보여").
// 두 줄이면 칸이 170px 이라 제목이 두 줄로 잘리고 값, 배지가 12px 대로 눌렸다. sm(640) 부터 둘.
const GRID_BASE = "grid grid-cols-1 gap-4 sm:grid-cols-2 sm:gap-x-4 md:grid-cols-3 md:gap-x-5 md:gap-y-6";
/** 필터 기둥 옆 목록(게임 목록) — 넓은 화면 3열 */
export const GAMES_GRID_CLASS = GRID_BASE;

// 홈 할인 격자. 280 이던 최소 폭을 목록과 같은 줄로 내렸다(2026-09-29) — 1200px 기둥에서 3열로 서면
// 카드 한 장이 380px 이 넘어 커버만 크고 한 화면에 여섯 장이 전부였다. 240 이면 4열이 선다.
// 세로 간격이 가로보다 넓은 이유: 카드가 hover 에서 4px 떠오르므로 줄 사이에 그 움직임이 앉을 자리가 필요하다
/** 기둥 없이 폭을 다 쓰는 격자(홈, 검색, 출시예정, 회사) — 넓은 화면 4열 */
export const HOME_GRID_CLASS = `${GRID_BASE} lg:grid-cols-4`;
