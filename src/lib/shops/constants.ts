// 매장 축의 수치 한 곳 — AGENTS §2. 화면과 서비스가 같은 값을 본다.

/**
 * 매장 찾기 한 쪽에 세우는 매장 수.
 *
 * 게임 목록(24)보다 작게 잡는다 — 매장 카드는 이름 한 줄이 아니라 주소, 연락처, 영업시간까지
 * 서너 줄이라 같은 수를 세우면 화면이 두 배로 길어진다. 입점 수가 이 값을 넘기 시작하면
 * 그때 거리순(좌표)을 먼저 붙인다. 쪽 넘기기로 매장을 찾게 두는 것은 답이 아니다.
 */
export const SHOPS_PAGE_SIZE = 12;

/**
 * 게임 상세의 "파는 곳" 에 세우는 매장 줄 수.
 *
 * 값이 싼 순으로 자른다 — 더 보여 줄 줄이 있어도 상세 화면의 다른 칸(가격 비교, DLC, 패치)을
 * 밀어내면서까지 세울 자리가 아니다. 다 보려면 매장 찾기로 간다.
 */
export const SELLING_PAGE_SIZE = 8;

/**
 * 직원 초대 링크의 수명(일).
 *
 * 메일이 아니라 사람이 메신저로 링크를 건네는 흐름이라(메일 수단이 레포에 없다) 받는 사람이
 * 그날 안 열 수 있다. 하루는 짧고, 한 달이면 그만둔 알바에게 보낸 링크가 너무 오래 산다.
 * 한 주면 "이번 주 안에 합류" 라는 매장 쪽 감각과 맞는다. 늘리지 말고 다시 보내게 한다.
 */
export const STAFF_INVITE_TTL_DAYS = 7;

/** 초대 토큰의 바이트 수. 세션 토큰(lib/auth/constants)과 같은 강도로 둔다 — 둘 다 "이걸 쥐면 들어온다" 다 */
export const STAFF_INVITE_TOKEN_BYTES = 32;

/**
 * CSV 한 번에 받는 줄 수 상한.
 *
 * 줄마다 판매 줄과 재고 이력을 쓰는 왕복이 붙는다. 운영(iad1, Neon us-east-1)에서 왕복이 한 자릿수 ms 라
 * 500줄이면 수 초 안에 끝나고 함수 시간 한도(300초)와 거리가 멀다. 이보다 큰 매장은 파일을 나눠 올리거나
 * 연동(설계서 §8)으로 넣을 일이다 — 손으로 관리하는 동네 매장 재고가 이 수를 넘는 일은 드물다.
 */
export const LISTING_CSV_MAX_ROWS = 500;

/** CSV 파일 크기 상한(바이트). 500줄 x 줄당 200바이트 남짓의 다섯 배 — 서버 액션 본문 한도(1MB) 안쪽이다 */
export const LISTING_CSV_MAX_BYTES = 512 * 1024;

/** 결과 화면에 적는 실패 줄 수. 넘는 것은 개수만 센다 — 500줄이 다 틀리면 화면이 오류로 덮인다 */
export const LISTING_CSV_ERROR_SAMPLE = 20;

/**
 * 카메라 스캔에서 한 장을 읽고 다음 장까지 쉬는 시간(ms).
 *
 * 매 프레임(16ms)마다 읽으면 저가 안드로이드에서 영상이 끊긴다. 사람이 바코드를 화면에 맞추는 데
 * 반 초는 걸리니 초당 다섯 번이면 기다림을 못 느낀다.
 */
export const BARCODE_SCAN_INTERVAL_MS = 200;

/**
 * 카메라가 찾을 바코드 종류. 게임 패키지에 붙는 것은 EAN 13(한국, 유럽, 일본 JAN 포함), UPC A(북미)이고,
 * 작은 물건에 EAN 8, UPC E 가 붙는다. QR 까지 찾으면 포장의 이벤트 QR 을 바코드로 읽는다.
 */
export const BARCODE_SCAN_FORMATS = ["ean_13", "ean_8", "upc_a", "upc_e"] as const;

/**
 * 판매 줄 하나에 붙이는 사진 장수 상한.
 *
 * 중고 한 물건을 앞, 뒤, 옆, 카트리지, 설명서, 흠집 정도로 찍으면 대여섯 장이다. 여덟이면 넉넉하고,
 * 매장 하나가 물건 500개를 올려도 4,000장이라 Blob 저장비(장당 300KB 남짓, 1.2GB)가 한 달 몇 센트다.
 */
export const LISTING_PHOTO_MAX = 8;

/**
 * 올리기 전에 브라우저에서 줄이는 긴 변(px). 휴대폰 원본(4000px 대, 3~8MB)을 그대로 올리면
 * 업로드가 느리고 손님 화면도 무겁다. 매장 페이지에서 가장 크게 보이는 자리가 800px 남짓이라
 * 레티나 두 배를 쳐도 1600 이면 된다.
 */
export const PHOTO_MAX_EDGE = 1600;

/** 줄인 사진의 압축 품질(0~1). 0.82 부근부터 글자(설명서, 라벨)가 뭉개지지 않으면서 파일이 300KB 안팎이 된다 */
export const PHOTO_QUALITY = 0.82;

/**
 * 업로드 토큰이 허락하는 한 장의 최대 크기. 줄인 뒤의 값이라 넉넉히 잡는다(1600px 사진이 이 크기를 넘는 일은 없다).
 * 토큰에 크기를 걸어 두는 이유: 줄이는 단계를 건너뛴 요청이 원본을 그대로 밀어 넣지 못하게.
 */
export const PHOTO_MAX_BYTES = 3 * 1024 * 1024;

/** 저장소가 받는 형식. 줄이는 단계가 이 둘 중 하나로 굽는다(사파리 구형은 webp 로 못 구워 jpeg 로 떨어진다) */
export const PHOTO_CONTENT_TYPES = ["image/webp", "image/jpeg"] as const;
